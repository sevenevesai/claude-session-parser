    #[test]
    fn hook_name_label_sanitizes_long_multiline_commands() {
        // /goal-style stop hook: command is a multi-line goal statement.
        // The synthesized hook_name must NOT include the full body — otherwise
        // every distinct goal creates a unique bucket and breaks the Usage page.
        let long_cmd = "Goal statement: Achieve >=3x better compression ratio than zstd -19 --long=27 and xz -9e on the Lichess 2024-01 corpus.\n\n3. Validation strategy:\n- (a) Fixed + held-out corpora.";
        let escaped = serde_json::to_string(long_cmd).unwrap();
        let summary = format!(
            r#"{{"type":"system","subtype":"stop_hook_summary","hookCount":1,"hookInfos":[{{"command":{escaped},"durationMs":42}}],"hookErrors":[],"preventedContinuation":false,"timestamp":"2026-04-25T12:00:00.000Z","uuid":"goal","toolUseID":"tu_goal","sessionId":"sess-goal","version":"2.1.119"}}"#
        );
        let asst = assistant_line("msg_goal", "claude-opus-4-6", "2026-04-25T12:00:01.000Z", 1, 1, 0, 0);
        let (_tmp, path) = write_jsonl(&[&summary, &asst]);

        let parsed = parse_jsonl_entries(&path).unwrap();
        assert_eq!(parsed.hooks.len(), 1);
        let h = &parsed.hooks[0];

        assert_eq!(h.command, long_cmd, "full command preserved on the entry");
        assert!(h.hook_name.starts_with("Stop:"), "name still scoped by event");
        // Total label length is bounded: event prefix + ":" + max 64 chars + 1-char ellipsis.
        assert!(h.hook_name.chars().count() <= "Stop:".len() + 65);
        assert!(h.hook_name.ends_with('…'), "long commands get ellipsis: {}", h.hook_name);
        assert!(!h.hook_name.contains('\n'), "no newlines in bucket key");
    }

