/// Pricing per 1M tokens (USD) by model family.
pub struct ModelPricing {
    pub input: f64,
    pub output: f64,
    pub cache_read: f64,
    pub cache_write: f64,
}

/// Hardcoded as of 2025-02. Requires a code change + release when Anthropic updates pricing.
pub fn pricing_for_model(model: &str) -> ModelPricing {
    if model.contains("opus") {
        ModelPricing {
            input: 5.0,
            output: 25.0,
            cache_read: 0.5,
            cache_write: 6.25,
        }
    } else if model.contains("haiku") {
        ModelPricing {
            input: 1.0,
            output: 5.0,
            cache_read: 0.1,
            cache_write: 1.25,
        }
    } else {
        // Sonnet or unknown
        ModelPricing {
            input: 3.0,
            output: 15.0,
            cache_read: 0.3,
            cache_write: 3.75,
        }
    }
}

pub fn context_window_for_model(model: &str) -> u64 {
    if model.contains("[1m]") {
        1_000_000
    } else {
        200_000
    }
}

/// Flat row representing a single completed assistant turn.
///
/// One entry per unique `message.id`. Claude Code writes multiple JSONL
/// entries per assistant message as the stream progresses (typically 2-3),
/// all sharing the same `id` and final usage numbers — dedup keeps only the
/// first occurrence.
///
/// Token field semantics (inherited from Anthropic's API):
/// - `input_tokens`: *fresh* tokens in this turn's prompt that were NOT served
///   from cache. Small when conversation is reused, large on cache misses.
/// - `cache_read_tokens`: tokens served from the prompt cache (cheap).
/// - `cache_write_tokens`: tokens written into the prompt cache (~25% premium).
/// - `output_tokens`: tokens generated by the model.
///
/// "Total context sent" for a turn = input + cache_read + cache_write.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct UsageEntry {
    pub session_id: String,
    /// Unix epoch ms from the JSONL `timestamp` field. 0 if unparseable.
    pub timestamp_ms: u64,
    pub model: String,
    pub input_tokens: u64,
    pub output_tokens: u64,
    pub cache_read_tokens: u64,
    pub cache_write_tokens: u64,
    /// Names of tools this turn invoked (from `tool_use` content blocks).
    /// Empty for pure-text turns. Duplicates preserved when the model called
    /// the same tool multiple times in one turn.
    pub tool_uses: Vec<String>,
    /// Sum of `text` content block character counts for this turn. Zero means
    /// a silent tool-only turn; non-zero means the model said something.
    pub text_chars: u32,
    /// Classified activity category (Coding, Debugging, Exploration, …).
    /// See the [`crate::activity`] module for the decision tree.
    pub activity: Activity,
    /// JSONL `entrypoint` field captured from the first row of each message id.
    /// `"cli"` = interactive Claude Code session. `"sdk-cli"` = headless
    /// `claude -p` spawn (any Agent SDK consumer lands here). `None` for legacy
    /// rows that predate the field. Useful for distinguishing interactive vs.
    /// headless usage; also load-bearing once Anthropic splits Agent SDK
    /// billing from interactive plans (announced June 2026).
    pub entrypoint: Option<String>,
}

/// A single hook execution event from a `type: "attachment"` JSONL record
/// where `attachment.type == "hook_success"`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HookExecution {
    pub session_id: String,
    pub timestamp_ms: u64,
    /// Lifecycle phase: `PreToolUse`, `PostToolUse`, `SessionStart`, `Stop`, etc.
    pub hook_event: String,
    /// Full hook label including matcher: `PreToolUse:Bash`, `Stop`, etc.
    pub hook_name: String,
    /// The shell command that was executed.
    pub command: String,
    pub exit_code: i32,
    pub duration_ms: u64,
    /// The tool-use ID that triggered this hook (groups multiple hooks per tool call).
    pub tool_use_id: Option<String>,
}

/// Combined result from parsing a single JSONL file.
#[derive(Default)]
pub struct ParsedJsonl {
    pub entries: Vec<UsageEntry>,
    pub hooks: Vec<HookExecution>,
}

