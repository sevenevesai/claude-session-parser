        assert_eq!(parsed.hooks.len(), 2, "two hook_success events");

        assert_eq!(parsed.hooks[0].hook_name, "PostToolUse:Edit");
        assert_eq!(parsed.hooks[0].hook_event, "PostToolUse");
        assert_eq!(parsed.hooks[0].command, "verify-edit.sh");
        assert_eq!(parsed.hooks[0].exit_code, 0);
        assert_eq!(parsed.hooks[0].duration_ms, 90);

        assert_eq!(parsed.hooks[0].tool_use_id.as_deref(), Some("tu_abc"));

        assert_eq!(parsed.hooks[1].hook_name, "PreToolUse:Bash");
        assert_eq!(parsed.hooks[1].exit_code, 1);
        assert_eq!(parsed.hooks[1].duration_ms, 250);
