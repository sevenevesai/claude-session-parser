/// Hard cap to avoid pathological parsing of a corrupted file.
///
/// Parsing is streaming (`BufReader::lines()`) so memory is O(1) per line —
/// the cap only exists to keep a runaway file from blocking the UI. Real
/// agent sessions (Task-tool sub-agents) frequently exceed 30MB, so the cap
/// needs generous headroom.
use super::MAX_JSONL_BYTES;

/// Encode a project path the same way Claude Code does.
///
/// Windows: `S:\Loom` -> `S--Loom`, `C:\Users\Seven\foo` -> `C--Users-Seven-foo`
/// macOS/Linux: `/Users/seven/Loom` -> `-Users-seven-Loom`, `/home/alice/proj` -> `-home-alice-proj`
///
/// The transform collapses any leading path separator(s) into a single leading
/// dash, which is how Claude Code writes `~/.claude/projects/` directory names
/// on Unix. Verified against ccusage's decoder (see GitHub issue
/// anthropics/claude-code#19972 for the path-encoding discussion).
pub fn encode_project_path(project_path: &str) -> String {
    let normalized = project_path.replace('/', "\\");
    let mut result = String::new();
    let mut chars = normalized.chars().peekable();

    while let Some(ch) = chars.next() {
        if ch == ':' {
            if chars.peek() == Some(&'\\') {
                chars.next();
                result.push_str("--");
            } else {
                result.push('-');
            }
        } else if ch == '\\' {
            result.push('-');
        } else {
            result.push(ch);
        }
    }

    while result.ends_with('-') {
        result.pop();
    }

    result
}

/// Extracted signal from an assistant message's `content` array.
struct AssistantContent {
    tool_uses: Vec<String>,
    bash_cmds: Vec<String>,
    text_chars: u32,
}

/// Walk an assistant message's content blocks to pull out tool names, any
/// bash-style commands (used by the classifier for Testing/GitOps/Build
/// detection), and the total character count of `text` blocks.
fn extract_assistant_content(content: Option<&serde_json::Value>) -> AssistantContent {
    let mut out = AssistantContent {
        tool_uses: Vec::new(),
        bash_cmds: Vec::new(),
        text_chars: 0,
    };
    let arr = match content.and_then(|v| v.as_array()) {
        Some(a) => a,
        None => return out,
    };

    for block in arr {
        let block_type = match block.get("type").and_then(|v| v.as_str()) {
            Some(t) => t,
            None => continue,
        };
        match block_type {
            "tool_use" => {
                if let Some(name) = block.get("name").and_then(|v| v.as_str()) {
                    // If this is a Bash-family tool, grab the command string so
                    // the classifier can distinguish Testing / GitOps / Build.
                    if matches!(name, "Bash" | "BashTool" | "PowerShellTool") {
                        if let Some(cmd) = block
                            .get("input")
                            .and_then(|i| i.get("command"))
                            .and_then(|c| c.as_str())
                        {
                            out.bash_cmds.push(cmd.to_string());
                        }
                    }
                    out.tool_uses.push(name.to_string());
                }
            }
            "text" => {
                if let Some(text) = block.get("text").and_then(|v| v.as_str()) {
                    // Saturating because a single turn's text can exceed u32
                    // only in pathological cases (would be >4 GB of text).
                    out.text_chars = out
                        .text_chars
                        .saturating_add(text.chars().count() as u32);
                }
            }
            _ => {}
        }
    }

    out
}

/// Extract the human-typed portion of a user message's content, if any.
///
/// User rows in Claude Code JSONL carry two distinct shapes:
/// - A plain string (`"content": "hello"`) — always a real user turn.
/// - An array of content blocks, which may be:
///   - `[{"type":"text","text":"..."}]` → real user turn
///   - `[{"type":"tool_result",...}]` → injected tool output, NOT a user turn
///   - Mixed → treated as a real user turn
///
/// Sanitize the per-hook `command` for use inside a synthesized `hook_name`
/// bucket key. Takes the first line, collapses internal whitespace, and caps
/// at 64 chars (with `…` suffix). The full command is preserved separately on
/// the `HookExecution.command` field — this only affects the display label /
/// aggregation key used by the Usage page and Refinery hook stats.
///
/// Without this, `/goal`-style hooks whose "command" is a multi-KB goal
/// statement explode the hook-table layout AND defeat aggregation (one bucket
/// per invocation).
fn sanitize_hook_command_label(cmd: &str) -> String {
    const MAX_LEN: usize = 64;
    let first_line = cmd.lines().next().unwrap_or("").trim();
    let collapsed: String = first_line.split_whitespace().collect::<Vec<_>>().join(" ");
    if collapsed.chars().count() <= MAX_LEN {
        return collapsed;
    }
    let truncated: String = collapsed.chars().take(MAX_LEN).collect();
    format!("{truncated}…")
}

/// Convert `snake_case` to `PascalCase`: `"stop"` → `"Stop"`, `"pre_tool_use"` → `"PreToolUse"`.
fn snake_to_pascal(s: &str) -> String {
    s.split('_')
        .filter(|w| !w.is_empty())
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                Some(first) => {
                    let mut out = first.to_uppercase().to_string();
                    out.extend(c);
                    out
                }
                None => String::new(),
            }
        })
        .collect()
}

/// Returns `None` for tool-result-only rows so the rolling `last_user_text`
/// stays pinned to the most recent actual user message.
fn extract_user_text(content: &serde_json::Value) -> Option<String> {
    match content {
        serde_json::Value::String(s) => {
            if s.is_empty() {
                None
            } else {
                Some(s.clone())
            }
        }
        serde_json::Value::Array(arr) => {
            let mut parts: Vec<&str> = Vec::new();
            for item in arr {
                let t = item.get("type").and_then(|v| v.as_str()).unwrap_or("");
                if t == "text" {
                    if let Some(text) = item.get("text").and_then(|v| v.as_str()) {
                        if !text.is_empty() {
                            parts.push(text);
                        }
                    }
                }
            }
            if parts.is_empty() {
                None
            } else {
                Some(parts.join(" "))
            }
        }
        _ => None,
    }
}

/// Per-message-id accumulator for content blocks that arrive split across
/// multiple JSONL rows. See `parse_jsonl_entries` for the why.
struct EntryAccumulator {
    out_idx: usize,
    bash_cmds: Vec<String>,
    user_text_at_first: Option<String>,
}

/// Parse a single JSONL file into one `UsageEntry` per unique `message.id`.
///
/// Pure function: depends only on the file contents. Non-assistant entries,
/// malformed lines, and missing IDs are skipped silently.
///
/// **Dedup is split by field semantics**, because Claude Code emits one JSONL
/// row per assistant content block (thinking / text / each tool_use) all
/// sharing the same `message.id`:
///
/// - Billing fields (token counts, model, timestamp, session_id) come from the
///   **first** row seen for each id — they repeat identically across rows.
/// - Content fields (`tool_uses`, `text_chars`, and the bash commands fed to
///   the activity classifier) are **unioned across every row** with that id,
///   then `activity` is classified once at the end using the merged content.
///
/// Folding only by `message.id` (as this parser did before 2026-05-13) drops
/// every tool_use after the first row, which made the Toolkit and Usage tool
/// counters undercount by an order of magnitude. The chat parser already
/// uses `(message_id + content)` for the same reason — see CLAUDE.md.
///
/// Runs a rolling `last_user_text` cursor during the stream: each genuine
/// `type: "user"` row updates it; the snapshot taken at the **first** row of
/// each assistant message is used for activity classification.
pub fn parse_jsonl_entries(path: &Path) -> std::io::Result<ParsedJsonl> {
    let meta = fs::metadata(path)?;
    if meta.len() > MAX_JSONL_BYTES {
        tracing::warn!(
            path = %path.display(),
            size = meta.len(),
            "skipping JSONL larger than {}MB",
            MAX_JSONL_BYTES / 1024 / 1024
        );
        return Ok(ParsedJsonl::default());
    }

    let file = fs::File::open(path)?;
    let reader = BufReader::new(file);

    let session_id = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("")
        .to_string();

    let mut accums: HashMap<String, EntryAccumulator> = HashMap::new();
    let mut out: Vec<UsageEntry> = Vec::new();
    let mut hooks: Vec<HookExecution> = Vec::new();
    let mut last_user_text: Option<String> = None;

    for line in reader.lines() {
        let line = match line {
            Ok(l) => l,
            Err(_) => continue,
        };
        let line = line.trim();
        if line.is_empty() {
            continue;
        }

        let raw: JsonlRaw = match serde_json::from_str(line) {
            Ok(r) => r,
            Err(_) => continue,
        };

        let entry_type = raw.entry_type.as_deref();

        // Update the rolling user-message cursor on genuine user turns.
        // Tool-result-only rows (also type="user") leave it untouched.
        if entry_type == Some("user") {
            if let Some(msg) = raw.message.as_ref() {
                if let Some(content) = msg.content.as_ref() {
                    if let Some(text) = extract_user_text(content) {
                        last_user_text = Some(normalize_user_text(&text));
                    }
                }
            }
            continue;
        }

        // Extract hook execution events from attachment records (v2.1.101 format).
        if entry_type == Some("attachment") {
            if let Some(att) = raw.attachment {
                if att.attachment_type.as_deref() == Some("hook_success") {
                    let timestamp_ms = raw
                        .timestamp
                        .as_deref()
                        .and_then(|s| DateTime::parse_from_rfc3339(s).ok())
                        .map(|dt| dt.timestamp_millis().max(0) as u64)
                        .unwrap_or(0);
                    hooks.push(HookExecution {
                        session_id: session_id.clone(),
                        timestamp_ms,
                        hook_event: att.hook_event.unwrap_or_default(),
                        hook_name: att.hook_name.unwrap_or_default(),
                        command: att.command.unwrap_or_default(),
                        exit_code: att.exit_code.unwrap_or(0),
                        duration_ms: att.duration_ms.unwrap_or(0),
                        tool_use_id: att.tool_use_id,
                    });
                }
            }
            continue;
        }

        // Extract hook summaries from system records (v2.1.119+ format).
        // Subtype pattern: "<event>_hook_summary" → hook_event = "<Event>".
        if entry_type == Some("system") {
            if let Some(subtype) = raw.subtype.as_deref() {
                if let Some(event_snake) = subtype.strip_suffix("_hook_summary") {
                    let hook_event = snake_to_pascal(event_snake);
                    let timestamp_ms = raw
                        .timestamp
                        .as_deref()
                        .and_then(|s| DateTime::parse_from_rfc3339(s).ok())
                        .map(|dt| dt.timestamp_millis().max(0) as u64)
                        .unwrap_or(0);
                    let had_errors = raw
                        .hook_errors
                        .as_ref()
                        .is_some_and(|e| !e.is_empty());
                    let prevented = raw.prevented_continuation.unwrap_or(false);
                    if let Some(infos) = raw.hook_infos {
                        for info in infos {
                            let cmd = info.command.unwrap_or_default();
                            let hook_name =
                                format!("{}:{}", hook_event, sanitize_hook_command_label(&cmd));
                            hooks.push(HookExecution {
                                session_id: session_id.clone(),
                                timestamp_ms,
                                hook_event: hook_event.clone(),
                                hook_name,
                                command: cmd,
                                exit_code: if had_errors || prevented { 1 } else { 0 },
                                duration_ms: info.duration_ms.unwrap_or(0),
                                tool_use_id: raw.tool_use_id.clone(),
                            });
                        }
                    }
                }
            }
            continue;
        }

        if entry_type != Some("assistant") {
            continue;
        }

        let msg = match raw.message {
            Some(m) => m,
            None => continue,
        };
        let mid = match msg.id {
            Some(id) => id,
            None => continue,
        };

        let mut content_parsed = extract_assistant_content(msg.content.as_ref());

        // Subsequent row for an already-seen message: union its content into
        // the existing entry. Billing/model/timestamp on the entry stay as-is.
        if let Some(acc) = accums.get_mut(&mid) {
            let entry = &mut out[acc.out_idx];
            entry
                .tool_uses
                .append(&mut content_parsed.tool_uses);
            entry.text_chars = entry
                .text_chars
                .saturating_add(content_parsed.text_chars);
            acc.bash_cmds.append(&mut content_parsed.bash_cmds);
            continue;
        }

        // Skip synthetic entries. Claude Code / the Agent SDK writes
        // `model: "<synthetic>"` rows for internal routing (skill listings,
        // queue ops, tool dispatch, etc.) — these never hit the LLM and have
        // all-zero token counts. Counting them would inflate turn counts
        // without representing real model activity.
        let model = msg.model.unwrap_or_default();
        if model == "<synthetic>" {
            continue;
        }

        let usage = msg.usage.unwrap_or_default();
        let timestamp_ms = raw
            .timestamp
            .as_deref()
            .and_then(|s| DateTime::parse_from_rfc3339(s).ok())
            .map(|dt| dt.timestamp_millis().max(0) as u64)
            .unwrap_or(0);

        // First row for this message: push placeholder entry with the content
        // we've seen so far. Activity is classified at the end of the file
        // against the merged content from all rows sharing this `message.id`.
        accums.insert(
            mid.clone(),
            EntryAccumulator {
                out_idx: out.len(),
                bash_cmds: std::mem::take(&mut content_parsed.bash_cmds),
                user_text_at_first: last_user_text.clone(),
            },
        );
        out.push(UsageEntry {
            session_id: session_id.clone(),
            timestamp_ms,
            model,
            input_tokens: usage.input_tokens.unwrap_or(0),
            output_tokens: usage.output_tokens.unwrap_or(0),
            cache_read_tokens: usage.cache_read_input_tokens.unwrap_or(0),
            cache_write_tokens: usage.cache_creation_input_tokens.unwrap_or(0),
            tool_uses: content_parsed.tool_uses,
            text_chars: content_parsed.text_chars,
            activity: Activity::General,
            entrypoint: raw.entrypoint.clone(),
        });
    }

    // Classify each accumulated entry using the merged content from all rows
    // that shared its `message.id`. Order doesn't matter — we mutate in place.
    for acc in accums.values() {
        let entry = &mut out[acc.out_idx];
        let tool_refs: Vec<&str> = entry.tool_uses.iter().map(|s| s.as_str()).collect();
        let bash_refs: Vec<&str> = acc.bash_cmds.iter().map(|s| s.as_str()).collect();
        entry.activity = classify(
            &tool_refs,
            &bash_refs,
            acc.user_text_at_first.as_deref(),
            entry.text_chars,
        );
    }

    Ok(ParsedJsonl {
        entries: out,
        hooks,
    })
}

/// Find the JSONL file for the current session by looking up Claude Code's
/// active sessions directory, matching on project path.
/// Falls back to finding the newest JSONL created after `spawned_at`.
pub fn find_current_session_jsonl(
    config_dir: &str,
    project_path: &str,
    spawned_at: SystemTime,
) -> Option<PathBuf> {
    let config = Path::new(config_dir);
    let encoded = encode_project_path(project_path);
    let projects_dir = config.join("projects").join(&encoded);

    if !projects_dir.exists() {
        return None;
    }

    // Strategy 1: Look up Claude Code's sessions/ directory for an active
    // session matching our project path. This gives us the exact session ID.
    let sessions_dir = config.join("sessions");
    if sessions_dir.exists() {
        if let Some(session_id) = find_active_session_id(&sessions_dir, project_path, spawned_at) {
            let jsonl_path = projects_dir.join(format!("{}.jsonl", session_id));
            if jsonl_path.exists() {
                return Some(jsonl_path);
            }
        }
    }

    // Strategy 2: Fall back to finding the earliest-created JSONL after spawn
    // time. "Earliest" is critical: with two concurrent sessions for the same
    // project, the older session must claim the first JSONL created after its
    // spawn, not the latest one (which belongs to the newer session).
    let mut candidates: Vec<(PathBuf, SystemTime)> = Vec::new();

    if let Ok(entries) = fs::read_dir(&projects_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("jsonl") {
                continue;
            }
            if let Ok(meta) = path.metadata() {
                let created = meta.created().unwrap_or(SystemTime::UNIX_EPOCH);
                if created >= spawned_at {
                    candidates.push((path, created));
                }
            }
        }
    }

    // Pick the earliest-created file after our spawn time
    candidates.sort_by(|a, b| a.1.cmp(&b.1));
    candidates.into_iter().next().map(|(p, _)| p)
}

/// Search Claude Code's sessions/ directory for an active session matching
/// the project path and started after our spawn time.
fn find_active_session_id(
    sessions_dir: &Path,
    project_path: &str,
    spawned_at: SystemTime,
) -> Option<String> {
    let spawned_ms = spawned_at
        .duration_since(SystemTime::UNIX_EPOCH)
        .ok()?
        .as_millis() as u64;

    // Allow 10s grace period (Claude Code may start slightly after PTY spawn)
    let threshold_ms = spawned_ms.saturating_sub(10_000);

    let normalized_project = normalize_path(project_path);

    let mut best: Option<(String, u64)> = None;

    if let Ok(entries) = fs::read_dir(sessions_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("json") {
                continue;
            }
            if let Ok(content) = fs::read_to_string(&path) {
                if let Ok(session) = serde_json::from_str::<ActiveSession>(&content) {
                    let session_cwd = normalize_path(&session.cwd);
                    if session_cwd == normalized_project && session.started_at >= threshold_ms {
                        // Pick the earliest session started after our spawn
                        // threshold. With multiple concurrent sessions for the
                        // same project, each has a different spawned_at: the
                        // older session's threshold is lower, so it must claim
                        // the first matching Claude session, not the latest one.
                        if best.as_ref().is_none_or(|(_, t)| session.started_at < *t) {
                            best = Some((session.session_id, session.started_at));
                        }
                    }
                }
            }
        }
    }

    best.map(|(id, _)| id)
}

/// Normalize a path for comparison: lowercase, forward slashes, no trailing slash.
fn normalize_path(p: &str) -> String {
    p.replace('\\', "/")
        .trim_end_matches('/')
        .to_lowercase()
}

/// Reduce a list of `UsageEntry` for a single session into a `SessionUsage`.
///
/// Preserves existing semantics:
/// - Primary model = the model used by the most messages (mode).
/// - Context window % uses the LAST entry's total input (API resends the full
///   conversation each turn; the last turn's input is the current usage).
/// - `launched_model` (from launch options) is used for context window sizing
///   because JSONL strips the `[1m]` suffix; fall back to mode when empty.
pub fn reduce_session(
    entries: &[UsageEntry],
    launched_model: &str,
    session_id_hint: &str,
) -> Option<SessionUsage> {
    if entries.is_empty() {
        return None;
    }

    let mut input_tokens = 0u64;
    let mut output_tokens = 0u64;
    let mut cache_read = 0u64;
    let mut cache_write = 0u64;
    let mut model_counts: HashMap<&str, u64> = HashMap::new();

    for e in entries {
        input_tokens += e.input_tokens;
        output_tokens += e.output_tokens;
        cache_read += e.cache_read_tokens;
        cache_write += e.cache_write_tokens;
        if !e.model.is_empty() {
            *model_counts.entry(e.model.as_str()).or_insert(0) += 1;
        }
    }

    let primary_model = model_counts
        .into_iter()
        .max_by_key(|(_, c)| *c)
        .map(|(m, _)| m.to_string())
        .unwrap_or_else(|| {
            entries
                .last()
                .map(|e| e.model.clone())
                .unwrap_or_default()
        });

    let pricing = pricing_for_model(&primary_model);
    let estimated_cost = (input_tokens as f64 * pricing.input
        + output_tokens as f64 * pricing.output
        + cache_read as f64 * pricing.cache_read
        + cache_write as f64 * pricing.cache_write)
        / 1_000_000.0;

    let context_model = if launched_model.is_empty() {
        &primary_model
    } else {
        launched_model
    };
    let context_window = context_window_for_model(context_model);

    let last = entries.last().unwrap();
    let last_context_used =
        last.input_tokens + last.cache_read_tokens + last.cache_write_tokens;
    let context_pct = if context_window > 0 {
        (last_context_used as f64 / context_window as f64 * 100.0).min(100.0)
    } else {
        0.0
    };

    let total = input_tokens + output_tokens + cache_read + cache_write;
    let total_context_sent = input_tokens + cache_read + cache_write;

    // Cache hit % reflects "what fraction of billable input-side tokens came
    // from cache". Denominator includes cache_write because writes are fresh
    // input being laid down for later reuse (billed at ~125% of input rate) —
    // they are NOT a hit. Only cache_read counts as reusing prior work.
    let cache_denom = input_tokens + cache_read + cache_write;
    let cache_hit_pct = if cache_denom > 0 {
        (cache_read as f64 / cache_denom as f64) * 100.0
    } else {
        0.0
    };

    let session_id = entries
        .first()
        .map(|e| e.session_id.clone())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| session_id_hint.to_string());

    Some(SessionUsage {
        model: primary_model,
        input_tokens,
        output_tokens,
        cache_read_tokens: cache_read,
        cache_write_tokens: cache_write,
        total_tokens: total,
        estimated_cost_usd: estimated_cost,
        context_window_size: context_window,
        context_window_used_pct: context_pct,
        current_context_tokens: last_context_used,
        total_context_sent,
        cache_hit_pct,
        message_count: entries.len() as u64,
        session_id,
    })
}

