    // ---------- split-row content merge (Claude Code one-block-per-row) ----------

    /// Helper: builds an assistant row that carries the same token usage
    /// numbers as the other rows for this `id` (matches what Claude Code
    /// actually writes — every row of a message repeats the final usage block).
    fn assistant_split_row(id: &str, ts: &str, content_json: &str) -> String {
        format!(
            r#"{{"type":"assistant","timestamp":"{ts}","message":{{"id":"{id}","model":"claude-opus-4-7","usage":{{"input_tokens":6,"output_tokens":746,"cache_read_input_tokens":21859,"cache_creation_input_tokens":33027}},"content":{content_json}}}}}"#
        )
    }

    #[test]
    fn parse_merges_tool_uses_across_split_content_rows() {
        // Claude Code 2.1.x emits one JSONL row per content block of an
        // assistant message: a `thinking` row, an optional `text` row, then
        // one row per `tool_use`. All rows share the same `message.id` and
        // the same `usage` block. The parser must merge tool_uses across rows
        // rather than dropping every row after the first.
        let thinking = assistant_split_row(
            "msg_01M6AvUVpAFjzSWcXeyGzUwV",
            "2026-05-13T09:09:03.500Z",
            r#"[{"type":"thinking","thinking":"plan"}]"#,
        );
        let text = assistant_split_row(
            "msg_01M6AvUVpAFjzSWcXeyGzUwV",
            "2026-05-13T09:09:03.550Z",
            r#"[{"type":"text","text":"Running tools in parallel."}]"#,
        );
        let tu1 = assistant_split_row(
            "msg_01M6AvUVpAFjzSWcXeyGzUwV",
            "2026-05-13T09:09:03.600Z",
            r#"[{"type":"tool_use","id":"tu_1","name":"mcp__example__list_configs","input":{"area":"rules"}}]"#,
        );
        let tu2 = assistant_split_row(
            "msg_01M6AvUVpAFjzSWcXeyGzUwV",
            "2026-05-13T09:09:03.700Z",
            r#"[{"type":"tool_use","id":"tu_2","name":"mcp__example__get_report","input":{}}]"#,
        );
        let tu3 = assistant_split_row(
            "msg_01M6AvUVpAFjzSWcXeyGzUwV",
            "2026-05-13T09:09:03.800Z",
            r#"[{"type":"tool_use","id":"tu_3","name":"Edit","input":{"file_path":"a.rs"}}]"#,
        );
        let (_tmp, path) = write_jsonl(&[&thinking, &text, &tu1, &tu2, &tu3]);

        let entries = parse_jsonl_entries(&path).unwrap().entries;
        assert_eq!(entries.len(), 1, "still one entry per message.id");

        let e = &entries[0];
        assert_eq!(
            e.tool_uses,
            vec![
                "mcp__example__list_configs".to_string(),
                "mcp__example__get_report".to_string(),
                "Edit".to_string(),
            ],
            "all tool_use names merged in row order"
        );
        assert!(e.text_chars > 0, "text from the text row is preserved");

        // Billing fields come from the first row (they repeat identically, so
        // first == last in practice). Importantly, the merged content must
        // NOT cause tokens to multiply.
        assert_eq!(e.input_tokens, 6);
        assert_eq!(e.output_tokens, 746);
        assert_eq!(e.cache_read_tokens, 21859);
        assert_eq!(e.cache_write_tokens, 33027);
    }

